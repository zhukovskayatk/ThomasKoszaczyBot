"""
"Дофаминовый блок": контент и логика наград за выполненную задачу.

Возвращает не просто текст, а целый "пакет" награды (см. SuccessReward) —
цитату/фразу и, если получится, ещё и медиа (стикер или картинку-мем).
Собирать сам текст сообщения и решать, ЧТО и КАК отправлять в чат —
задача handlers/tasks.py, здесь только контент и его случайный выбор.
"""

import random
from dataclasses import dataclass
from pathlib import Path

# --- Цитаты / фразы-похвалы --------------------------------------------------
#
# ToV: понимающий друг для человека с СДВГ — не токсичный "просто соберись",
# а смесь лёгкой иронии над бытовыми трудностями и настоящей поддержки.
# Часть фраз — с юмором про "мозг с СДВГ", часть — просто тёплые.
SUCCESS_PHRASES = [
    # Ироничные, про специфику СДВГ-мозга
    "Задача пала смертью храбрых. Ты — герой. 🏆",
    "Ещё одна победа над хаосом. СДВГ-мозг сегодня в ударе! ⚡",
    "Гештальт закрыт. Вселенная стала чуточку добрее. ✨",
    "Продуктивность +100, тревожность −100. Отличный обмен. 🔥",
    "Задача исчезла. Как по волшебству. Только это не магия, это ты. 🪄",
    "Ещё +10 к внутреннему ГГ этого дня. 🎮",
    "Один маленький шаг для тебя, один огромный — для твоего списка дел. 🚀",
    "Отвлекающие мысли пытались помешать. Не сегодня. 🧠🛡",
    "Прокрастинация проиграла этот раунд. 1:0 в твою пользу. 🥇",
    # Тёплые, поддерживающие — без иронии
    "Ты сделал(а) это. Даже без дедлайна над головой. Легенда. 🐐",
    "Это было непросто, но ты справил(ась)ся. Мозг говорит спасибо. 🧠💙",
    "Так, а теперь можно и чай. Заслужил(а). ☕",
    "Маленькая задача — но её больше нет в голове, а это дорогого стоит. 💛",
    "Не важно, что это заняло время. Важно, что это сделано. 🌱",
    "Каждый закрытый гештальт делает мир чуть спокойнее. 🔥",
    "Горжусь тобой. Без шуток. 🤍",
]

# --- Стикеры/гифки поздравления -----------------------------------------------
#
# У каждого стикера/гифки в Telegram есть свой уникальный file_id — по нему
# бот может отправлять его повторно, не загружая заново. Список специально
# начинается ПУСТЫМ: настоящие file_id нужно собрать из реальных стикеров.
#
# Как собрать: запусти бота и пришли ЕМУ в чат любой понравившийся стикер —
# в ответ придёт его file_id (см. handlers/dev_tools.py). Скопируй строку
# сюда, в список — и стикер тут же станет частью пула наград, без
# перезапуска бота ничего больше делать не надо.
STICKER_IDS: list[str] = [
    # "CAACAgIAAxkBAAIB...",  # например, сюда — file_id довольного кота
]

# --- Локальные картинки-мемы ---------------------------------------------------
#
# Папка assets/memes/ рядом с проектом — просто скидывай туда свои любимые
# мем-картинки (.jpg/.jpeg/.png/.gif/.webp), ничего в коде менять не нужно.
# Список файлов сканируется заново при каждой награде, так что новые файлы
# подхватываются сразу же, без перезапуска бота.
ASSETS_MEMES_DIR = Path(__file__).resolve().parent.parent / "assets" / "memes"
MEME_FILE_EXTENSIONS = {".jpg", ".jpeg", ".png", ".gif", ".webp"}


def _list_local_memes() -> list[Path]:
    """Возвращает список файлов-картинок в assets/memes/ (или [], если папки нет/она пуста)."""
    if not ASSETS_MEMES_DIR.is_dir():
        return []
    return sorted(
        p for p in ASSETS_MEMES_DIR.iterdir()
        if p.is_file() and p.suffix.lower() in MEME_FILE_EXTENSIONS
    )


@dataclass
class SuccessReward:
    """
    "Пакет" награды за выполненную задачу.

    phrase — цитата/фраза, есть ВСЕГДА.
    sticker_id / meme_path — медиа, которое нужно приложить (максимум
    ОДНО из двух, оба могут быть None, если ни стикеров, ни картинок
    ещё не настроено — тогда награда будет просто текстовой).
    """
    phrase: str
    sticker_id: str | None = None
    meme_path: Path | None = None


def get_success_reward() -> SuccessReward:
    """
    Собирает случайную награду: всегда — фраза, и, если есть из чего
    выбирать, — либо стикер, либо картинка-мем (см. handlers/tasks.py,
    там решается, каким именно способом их отправлять в Telegram).

    Стикеры и локальные картинки участвуют в выборе НА РАВНЫХ — просто
    единый пул возможных "медиа-подарков", из которого берётся один
    случайный вариант (или ни одного, если пул пуст).
    """
    phrase = random.choice(SUCCESS_PHRASES)

    media_candidates: list[tuple[str, str | Path]] = [
        ("sticker", sticker_id) for sticker_id in STICKER_IDS
    ] + [
        ("photo", meme_path) for meme_path in _list_local_memes()
    ]

    if not media_candidates:
        return SuccessReward(phrase=phrase)

    kind, payload = random.choice(media_candidates)
    if kind == "sticker":
        return SuccessReward(phrase=phrase, sticker_id=payload)
    return SuccessReward(phrase=phrase, meme_path=payload)