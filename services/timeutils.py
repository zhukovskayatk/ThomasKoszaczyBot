"""
Перевод времени между часовым поясом СЕРВЕРА (на котором физически крутится
бот — каким бы он ни был настроен) и ЛИЧНЫМ часовым поясом конкретного
пользователя (User.utc_offset_minutes, настройка "🌍 Часовой пояс" в
Профиле, см. handlers/profile.py).

Почему это вообще понадобилось: раньше весь бот везде использовал
datetime.now()/date.today() — то есть буквально системное время машины, на
которой он запущен. Если часовой пояс сервера не совпадает с реальным
часовым поясом человека (а знать заранее, что там на сервере, не
обязательно — сервер мог быть поднят где угодно, с любым системным TZ),
дедлайны и напоминания сохранялись и срабатывали "по серверу", то есть на
деле — в чужом часовом поясе. Причём тут ни при чём VPN сам по себе: бот
никогда не спрашивал часовой пояс телефона, он всегда молча предполагал,
что "сейчас" сервера и "сейчас" у человека — одно и то же.

Решение — НЕ трогать то, как всё уже хранится и планируется (Task.deadline,
Reminder.remind_at как были в "серверном" времени и передаются в
APScheduler напрямую — так и остаются, ничего не мигрируем и не рискуем
сломать уже отлаженную логику планировщика). Вместо этого — тонкий слой
перевода ровно на ДВУХ границах:
- ВВОД: когда человек лично выбирает дату/время (календарь, барабан
  времени, быстрые пресеты, "уже прошло?", распознавание ИИ) — то, что он
  выбрал, ИМЕННО В ЕГО часовом поясе, переводится в серверное ПЕРЕД
  сохранением/постановкой в планировщик (см. to_server).
- ВЫВОД: когда дедлайн уже сохранённой задачи показывается человеку
  (карточка, список, подтверждения) — серверное время переводится ОБРАТНО
  в его личный часовой пояс ПЕРЕД рендерингом текста (см. to_user/
  localize_task/localize_tasks). Общая (партнёрская) задача при этом
  показывается каждому в ЕГО СОБСТВЕННЫХ часах — как в любом обычном
  календаре, а не в часах того, кто её создал.

server_offset_minutes() вычисляется на лету через разницу datetime.now() и
datetime.utcnow() — то есть работает одинаково корректно вне зависимости от
того, в каком часовом поясе на самом деле настроен сервер: не нужно ни
знать его заранее, ни хардкодить, ни просить кого-то проверять
timedatectl на сервере.

Задачи "☀️ В течение дня" (deadline_all_day=True) сознательно ВНЕ
масштаба этого перевода — см. docstring localize_task ниже.
"""

from datetime import datetime, timedelta

from database.requests import get_user

# Часовой пояс по умолчанию для новых пользователей — UTC+3 (Москва),
# самый частый случай для этого бота (см. database.models.User.
# utc_offset_minutes, там то же значение по умолчанию для новых записей).
# Здесь используется как безопасный fallback, если пользователь почему-то
# не нашёлся в БД, вместо падения с ошибкой.
DEFAULT_OFFSET_MINUTES = 180

# Разумные границы шага в настройке "🌍 Часовой пояс" (см. handlers/profile.py
# tz_adjust) — от Бейкер-Айленда (UTC-12) до Кирибати (UTC+14).
MIN_OFFSET_MINUTES = -12 * 60
MAX_OFFSET_MINUTES = 14 * 60
STEP_MINUTES = 60


def server_offset_minutes() -> int:
    """Текущее смещение системного времени сервера от UTC, в минутах —
    вычисляется на лету, а не хранится/хардкодится (см. docstring модуля)."""
    delta = datetime.now() - datetime.utcnow()
    return round(delta.total_seconds() / 60)


def user_now(offset_minutes: int) -> datetime:
    """
    "Сейчас" в личном часовом поясе пользователя — то же самое, что вернул
    бы datetime.now(), если бы сервер физически стоял в его часовом поясе.
    Используется вместо datetime.now()/date.today() везде, где нужно
    "сейчас глазами конкретного человека": уже прошло ли выбранное время,
    разумное время по умолчанию, контекст для ИИ-распознавания дат.
    """
    return datetime.now() + timedelta(minutes=offset_minutes - server_offset_minutes())


def to_server(user_dt: datetime, offset_minutes: int) -> datetime:
    """
    Переводит "наивное" время, выбранное пользователем В ЕГО ЧАСОВОМ
    ПОЯСЕ (календарь/барабан времени, "завтра 09:00" и т.п.), в время
    сервера — именно в этом виде оно попадает в БД (Task.deadline,
    Reminder.remind_at) и в APScheduler (run_date), как и раньше.
    """
    return user_dt + timedelta(minutes=server_offset_minutes() - offset_minutes)


def to_user(server_dt: datetime, offset_minutes: int) -> datetime:
    """
    Обратный перевод — время сервера (как оно хранится в БД) обратно в
    личный часовой пояс конкретного пользователя, ДЛЯ ОТОБРАЖЕНИЯ. Для
    общей (партнёрской) задачи вызывается с часовым поясом именно того,
    кто сейчас СМОТРИТ на экран, а не владельца задачи.
    """
    return server_dt + timedelta(minutes=offset_minutes - server_offset_minutes())


async def viewer_offset_minutes(user_id: int) -> int:
    """Личный часовой пояс пользователя (User.utc_offset_minutes) — с
    безопасным дефолтом (DEFAULT_OFFSET_MINUTES), если запись почему-то не
    найдена в БД, вместо падения."""
    user = await get_user(user_id)
    return user.utc_offset_minutes if user is not None else DEFAULT_OFFSET_MINUTES


def localize_task(task, offset_minutes: int):
    """
    Переводит task.deadline из времени СЕРВЕРА в личный часовой пояс ТОГО,
    кто сейчас смотрит на экран. Мутирует объект НА МЕСТЕ и ничего не
    пишет обратно в БД (объект уже вне сессии, изменение только в памяти
    процесса) — вызывать строго ПОСЛЕДНИМ шагом перед рендерингом текста/
    клавиатуры: до этого момента task.deadline ещё "серверный" и годится
    для сравнений с available_reminder_offsets/datetime.now().

    Задачи "☀️ В течение дня" (deadline_all_day) сознательно
    ПРОПУСКАЮТСЯ: у них нет точного часа, который имело бы смысл
    переводить (весь смысл этой пометки — что час не важен), а сам
    дедлайн при СОЗДАНИИ такой задачи тоже никогда не переводился между
    часовыми поясами (см. handlers/tasks.py::_save_all_day_deadline) —
    перевод одной только даты рядом с полуночью мог бы случайно сдвинуть
    день целиком, а выигрыш для задачи без точного часа минимальный.
    Поэтому весь модуль "в течение дня" сознательно вне масштаба этого
    перевода часовых поясов.
    """
    if task is not None and task.deadline is not None and not task.deadline_all_day:
        task.deadline = to_user(task.deadline, offset_minutes)
    return task


def localize_tasks(tasks, offset_minutes: int):
    """Localize_task для целого списка задач — см. localize_task."""
    for task in tasks:
        localize_task(task, offset_minutes)
    return tasks
